// Generates src/data/videoAudio.js — the set of case-study videos that carry
// *audible* audio (not just a silent AAC track). A file only makes the list if
// its peak volume clears the silence threshold. Re-run after adding/replacing
// videos in public/cs/:  node scripts/gen-video-audio.mjs
import { readdirSync, writeFileSync } from 'node:fs'
import { execSync } from 'node:child_process'
import { join, relative } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const CS_DIR = join(ROOT, 'public/cs')
const SILENCE_DB = -50 // max_volume at or below this = treat as silent

function walk(dir) {
  const out = []
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) out.push(...walk(p))
    else if (e.name.toLowerCase().endsWith('.mp4')) out.push(p)
  }
  return out
}

function maxVolumeDb(file) {
  // No audio stream → -Infinity (silent).
  try {
    const probe = execSync(`ffprobe -v error -select_streams a -show_entries stream=codec_name -of csv=p=0 "${file}"`, { encoding: 'utf8' }).trim()
    if (!probe) return -Infinity
  } catch { return -Infinity }
  try {
    // volumedetect reports on stderr — merge it into stdout with 2>&1.
    const out = execSync(`ffmpeg -hide_banner -nostats -i "${file}" -map 0:a:0 -af volumedetect -f null - 2>&1`, { encoding: 'utf8' })
    const m = out.match(/max_volume:\s*(-?[\d.]+) dB/)
    return m ? Number(m[1]) : -Infinity
  } catch { return -Infinity }
}

const files = walk(CS_DIR).sort()
const audible = []
for (const f of files) {
  const db = maxVolumeDb(f)
  const webPath = '/' + relative(join(ROOT, 'public'), f)
  if (db > SILENCE_DB) audible.push(webPath)
  console.log(`${db === -Infinity ? '  --  ' : db.toFixed(1).padStart(6)} dB  ${webPath}`)
}

const body = `// AUTO-GENERATED by scripts/gen-video-audio.mjs — do not edit by hand.
// Case-study videos whose audio is actually audible (peak > ${SILENCE_DB} dB).
// Silent/track-less clips are omitted so their mute button is hidden.
export const REAL_AUDIO_VIDEOS = new Set([
${audible.map(p => `  '${p}',`).join('\n')}
])
`
writeFileSync(join(ROOT, 'src/data/videoAudio.js'), body)
console.log(`\nWrote src/data/videoAudio.js — ${audible.length} audible of ${files.length} videos.`)
